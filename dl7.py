total_losses = [r + k for r, k in zip(recon_losses_per_epoch, kl_losses_per_epoch)]
axes[2].plot(epochs_range, total_losses, 'g-o', linewidth=2, markersize=5, label='Total Loss')
axes[2].plot(epochs_range, recon_losses_per_epoch, 'b--', linewidth=1.5, alpha=0.6, label='Recon')
axes[2].plot(epochs_range, kl_losses_per_epoch,    'r--', linewidth=1.5, alpha=0.6, label='KL')
axes[2].set_title('All Losses Combined')
axes[2].set_xlabel('Epoch')
axes[2].set_ylabel('Loss')
axes[2].legend()
axes[2].grid(True, alpha=0.3)

plt.tight_layout()
plt.savefig('2_loss_curves.png', dpi=120)
plt.show()
