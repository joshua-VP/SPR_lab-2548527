import torch
import torch.nn as nn
import torch.optim as optim
from torchvision import datasets, transforms
from torch.utils.data import DataLoader
import matplotlib.pyplot as plt
import numpy as np

#Dataset
transform  = transforms.ToTensor()
train_data = datasets.MNIST(root='./data', train=True,  download=True, transform=transform)
test_data  = datasets.MNIST(root='./data', train=False, download=True, transform=transform)
train_loader = DataLoader(train_data, batch_size=128, shuffle=True)
test_loader  = DataLoader(test_data,  batch_size=16,  shuffle=True)

class Encoder(nn.Module):
    def __init__(self, input_dim=784, hidden_dim=400, latent_dim=20):
        super().__init__()
        self.fc        = nn.Linear(input_dim, hidden_dim)
        self.fc_mu     = nn.Linear(hidden_dim, latent_dim)
        self.fc_logvar = nn.Linear(hidden_dim, latent_dim)
        self.relu      = nn.ReLU()

    def forward(self, x):
        h       = self.relu(self.fc(x))
        mu      = self.fc_mu(h)
        log_var = self.fc_logvar(h)
        return mu, log_var

def reparameterize(mu, log_var):
    std = torch.exp(0.5 * log_var)
    eps = torch.randn_like(std)
    return mu + eps * std

class Decoder(nn.Module):
    def __init__(self, latent_dim=20, hidden_dim=400, output_dim=784):
        super().__init__()
        self.fc1     = nn.Linear(latent_dim, hidden_dim)
        self.fc2     = nn.Linear(hidden_dim, output_dim)
        self.relu    = nn.ReLU()
        self.sigmoid = nn.Sigmoid()

    def forward(self, z):
        h = self.relu(self.fc1(z))
        return self.sigmoid(self.fc2(h))

class VAE(nn.Module):
    def __init__(self):
        super().__init__()
        self.encoder = Encoder()
        self.decoder = Decoder()

    def forward(self, x):
        x = x.view(-1, 784)
        mu, log_var = self.encoder(x)
        z = reparameterize(mu, log_var)
        x_recon = self.decoder(z)
        return x_recon, mu, log_var

def vae_loss(x_recon, x, mu, log_var):
    x_flat     = x.view(-1, 784)
    recon_loss = nn.functional.binary_cross_entropy(x_recon, x_flat, reduction='sum')
    kl_loss    = -0.5 * torch.sum(1 + log_var - mu.pow(2) - log_var.exp())
    return recon_loss, kl_loss

device    = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
model     = VAE().to(device)
optimizer = optim.Adam(model.parameters(), lr=1e-3)

sample_imgs, sample_labels = next(iter(test_loader))
fig, axes = plt.subplots(2, 8, figsize=(14, 4))
fig.suptitle('Sample MNIST Input Images', fontsize=14, fontweight='bold')
for i in range(16):
    ax = axes[i // 8][i % 8]
    ax.imshow(sample_imgs[i].squeeze(), cmap='gray')
    ax.set_title(f'Label: {sample_labels[i].item()}', fontsize=8)
    ax.axis('off')
plt.tight_layout()
plt.savefig('1_input_images.png', dpi=120)
plt.show()
