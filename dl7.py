EPOCHS = 10
recon_losses_per_epoch = []
kl_losses_per_epoch    = []

print(f"\nTraining on: {device}")
print("=" * 60)

for epoch in range(1, EPOCHS + 1):
    model.train()
    total_recon = total_kl = 0

    for x, _ in train_loader:
        x = x.to(device)
        x_recon, mu, log_var = model(x)

        recon_loss, kl_loss = vae_loss(x_recon, x, mu, log_var)
        loss = recon_loss + kl_loss

        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        total_recon += recon_loss.item()
        total_kl    += kl_loss.item()

    n = len(train_loader.dataset)
    avg_recon = total_recon / n
    avg_kl    = total_kl    / n

    recon_losses_per_epoch.append(avg_recon)
    kl_losses_per_epoch.append(avg_kl)

    print(f"Epoch {epoch:02d}/{EPOCHS} | "
          f"Reconstruction Loss: {avg_recon:.4f} | "
          f"KL Divergence Loss:  {avg_kl:.4f} | "
          f"Total: {avg_recon + avg_kl:.4f}")

print("=" * 60)
print("Training complete!")

epochs_range = range(1, EPOCHS + 1)
fig, axes = plt.subplots(1, 3, figsize=(16, 4))
fig.suptitle('VAE Training Loss Curves', fontsize=14, fontweight='bold')

axes[0].plot(epochs_range, recon_losses_per_epoch, 'b-o', linewidth=2, markersize=5, label='Recon Loss')
